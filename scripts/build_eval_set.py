"""Phase 3: build data/eval/questions.jsonl from the independent and generated question sets.

  .venv/Scripts/python scripts/build_eval_set.py --generate   # top up the generated set with the LLM, then build
  .venv/Scripts/python scripts/build_eval_set.py              # rebuild from the two CSV files
  .venv/Scripts/python scripts/build_eval_set.py --independent-only # independent set only (no API key needed)
"""
import argparse
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from copilot import config  # noqa: E402
from copilot.attack import bundle_path, load_techniques, retired_ids, revoked_successors  # noqa: E402
from copilot.evals.dataset import DatasetError, assign_splits, read_csv, save_questions, validate  # noqa: E402
from copilot.evals.generate import make_question, sample_techniques  # noqa: E402

EVAL_DIR = config.ROOT / "data" / "eval"
INDEPENDENT_CSV = EVAL_DIR / "independent_questions.csv"
GENERATED_CSV = EVAL_DIR / "generated_questions.csv"
# 25 independent + 308 generated = 333 questions; a 30% test split is then 100.
N_GENERATED = 308
SEED = 13


def generate(techniques, exclude: set[str]) -> None:
    """Top the generated set up to N_GENERATED, one new technique per question.

    Existing rows are kept and each new row is appended as soon as it is
    written, so an interrupted run (rate limits, network) resumes where it
    stopped instead of starting over.
    """
    from copilot.llm import get_provider

    existing = read_csv(GENERATED_CSV, source="generated") if GENERATED_CSV.exists() else []
    if not existing:
        with open(GENERATED_CSV, "w", encoding="utf-8", newline="") as f:
            csv.writer(f).writerow(["question", "technique_id", "note"])
    needed = N_GENERATED - len(existing)
    if needed <= 0:
        print(f"generated set already has {len(existing)} questions")
        return

    provider = get_provider()
    used = exclude | {q.technique_id for q in existing}
    # Sample spares so a technique the model cannot describe without naming it can be skipped.
    candidates = sample_techniques(techniques, needed + 30, used, seed=SEED)
    done = 0
    with open(GENERATED_CSV, "a", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, quoting=csv.QUOTE_MINIMAL)
        for t in candidates:
            if done == needed:
                break
            question = make_question(t, provider)
            if not question:
                print(f"  skipped {t.id} ({t.name}): model kept naming the technique", flush=True)
                continue
            writer.writerow([question, t.id, f"generated by {provider.model}"])
            f.flush()
            done += 1
            print(f"  [{len(existing) + done:>3}/{N_GENERATED}] {t.id:<10} {question[:80]}", flush=True)
    print(f"added {done} questions to {GENERATED_CSV.relative_to(config.ROOT)}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--generate", action="store_true", help="top up the generated set with the configured LLM")
    parser.add_argument("--independent-only", action="store_true", help="build from the independent set only")
    args = parser.parse_args()

    path = bundle_path()
    techniques = load_techniques(path)
    independent = read_csv(INDEPENDENT_CSV, source="independent")

    if args.generate:
        generate(techniques, exclude={q.technique_id for q in independent})
    questions = independent if args.independent_only else independent + read_csv(GENERATED_CSV, source="generated")

    try:
        validate(questions, techniques, retired_ids(path), revoked_successors(path))
    except DatasetError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    questions = assign_splits(questions, seed=SEED)
    save_questions(questions)
    for source in sorted({q.source for q in questions}):
        subset = [q for q in questions if q.source == source]
        print(f"{source:<10} {len(subset):>3}  dev {sum(q.split == 'dev' for q in subset):>2}  "
              f"test {sum(q.split == 'test' for q in subset):>2}")
    print(f"total      {len(questions):>3}  -> data/eval/questions.jsonl")
    return 0


if __name__ == "__main__":
    sys.exit(main())
