"""Phase 3: build data/eval/questions.jsonl from the hand-written and generated questions.

  .venv/Scripts/python scripts/build_eval_set.py --generate   # write the generated set with the LLM, then build
  .venv/Scripts/python scripts/build_eval_set.py              # rebuild from the two CSV files
  .venv/Scripts/python scripts/build_eval_set.py --owner-only # hand-written questions only (no API key needed)
"""
import argparse
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from copilot import config  # noqa: E402
from copilot.attack import bundle_path, load_techniques, retired_ids, revoked_successors  # noqa: E402
from copilot.evals.dataset import DatasetError, assign_splits, read_csv, save_questions, validate  # noqa: E402
from copilot.evals.generate import make_question, sample_techniques  # noqa: E402

EVAL_DIR = config.ROOT / "data" / "eval"
OWNER_CSV = EVAL_DIR / "owner_questions.csv"
GENERATED_CSV = EVAL_DIR / "generated_questions.csv"
N_GENERATED = 75
SEED = 13


def generate(techniques, exclude: set[str]) -> None:
    from copilot.llm import get_provider

    provider = get_provider()
    # Sample spares so a technique the model cannot describe without naming it can be skipped.
    candidates = sample_techniques(techniques, N_GENERATED + 15, exclude, seed=SEED)
    rows = []
    for t in candidates:
        if len(rows) == N_GENERATED:
            break
        question = make_question(t, provider)
        if question:
            rows.append((question, t.id, f"generated by {provider.model}"))
            print(f"  [{len(rows):>2}/{N_GENERATED}] {t.id:<10} {question[:90]}")
        else:
            print(f"  skipped {t.id} ({t.name}): model kept naming the technique")
    with open(GENERATED_CSV, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, quoting=csv.QUOTE_MINIMAL)
        writer.writerow(["question", "technique_id", "note"])
        writer.writerows(rows)
    print(f"wrote {len(rows)} questions to {GENERATED_CSV.relative_to(config.ROOT)}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--generate", action="store_true", help="(re)write the generated set with the configured LLM")
    parser.add_argument("--owner-only", action="store_true", help="build from the hand-written questions only")
    args = parser.parse_args()

    path = bundle_path()
    techniques = load_techniques(path)
    owner = read_csv(OWNER_CSV, source="owner")

    if args.generate:
        generate(techniques, exclude={q.technique_id for q in owner})
    questions = owner if args.owner_only else owner + read_csv(GENERATED_CSV, source="generated")

    try:
        validate(questions, techniques, retired_ids(path), revoked_successors(path))
    except DatasetError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    questions = assign_splits(questions, seed=SEED)
    save_questions(questions)
    for source in sorted({q.source for q in questions}):
        subset = [q for q in questions if q.source == source]
        print(f"{source:<10} {len(subset):>3}  dev {sum(q.split == 'dev' for q in subset):>2}  "
              f"test {sum(q.split == 'test' for q in subset):>2}")
    print(f"total      {len(questions):>3}  -> data/eval/questions.jsonl")
    return 0


if __name__ == "__main__":
    sys.exit(main())
