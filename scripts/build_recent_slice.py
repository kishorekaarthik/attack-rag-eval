"""Build the recent-techniques slice: one question per technique added or renumbered in ATT&CK v19 and v20.

  .venv/Scripts/python scripts/build_recent_slice.py

"Added or renumbered in the last two releases" = active in the pinned v20.1
but not active in v18.1, the last release before v19. That covers techniques
created in v19/v20 and the new IDs given to revoked ones (e.g. T1562.001 ->
T1685). Only 6 test questions fall in this group, too few to measure, so this
slice gets its own questions. It is kept outside the 333-question set and is
never used for tuning or selection. Questions are generated with the same
model and leak check as the generated set.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from copilot import config  # noqa: E402
from copilot.attack import bundle_path, load_techniques, retired_ids, revoked_successors  # noqa: E402
from copilot.evals.dataset import Question, load_questions, save_questions, validate  # noqa: E402
from copilot.evals.generate import make_question  # noqa: E402
from copilot.llm import get_provider  # noqa: E402

BEFORE = "18.1"
RECENT_PATH = config.ROOT / "data" / "eval" / "recent_questions.jsonl"


def recent_techniques():
    current = load_techniques(bundle_path(config.ATTACK_VERSION))
    before = {t.id for t in load_techniques(bundle_path(BEFORE))}
    successors = revoked_successors(bundle_path(config.ATTACK_VERSION))
    renumbered = set(successors.values())
    return [t for t in current if t.id not in before], renumbered


def main() -> int:
    techniques, renumbered = recent_techniques()
    existing = {q.technique_id: q for q in load_questions(RECENT_PATH)} if RECENT_PATH.exists() else {}
    provider = get_provider()
    questions = []
    for t in techniques:
        if t.id in existing:
            questions.append(existing[t.id])
            continue
        text = make_question(t, provider)
        if not text:
            print(f"  skipped {t.id} ({t.name}): model kept naming the technique")
            continue
        kind = "renumbered" if t.id in renumbered else "new"
        questions.append(Question(id=f"r{len(questions) + 1:03d}", question=text, technique_id=t.id,
                                  source="recent", split="recent", note=f"{kind}; generated by {provider.model}"))
        print(f"  {t.id:<10} {kind:<10} {text[:80]}", flush=True)
        save_questions(questions, RECENT_PATH)

    path = bundle_path(config.ATTACK_VERSION)
    validate(questions, load_techniques(path), retired_ids(path), revoked_successors(path))
    save_questions(questions, RECENT_PATH)
    n_renum = sum(q.note.startswith("renumbered") for q in questions)
    print(f"{len(questions)} questions ({n_renum} renumbered, {len(questions) - n_renum} new) "
          f"-> {RECENT_PATH.relative_to(config.ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
